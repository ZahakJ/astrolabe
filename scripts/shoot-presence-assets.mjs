// Renders the Discord presence images: docs/brand/presence/*.svg → *.png at
// 1024×1024, the size the Developer Portal asks for and the files the pages
// site serves (shared/presence/config.ts `${PRESENCE_ASSET_BASE}${name}.png`).
//
//   CHROMIUM=/usr/bin/chromium node scripts/shoot-presence-assets.mjs
//
// THE MARK is not drawn by hand: mark.svg is written here from
// shared/brandMark.ts, the one geometry every face of the product uses, on
// the app icon's plate (desktop/icons/make-icon.mjs — the same 22% corner and
// the same 12% of air around the drawing), gold on graphite.
//
// THE EIGHT GLYPHS are the hand-written SVGs beside it (pen, page, book,
// cards, brush, shelf, compass, moon): strokes in the mark's own language,
// round caps and joins at 6% of the canvas, on a graphite DISC because
// Discord crops the small image to a circle and shows it at about 20 px.
// Edit the SVG, run this, commit both.
//
// One browser, one page, one file after another (the machine's two-browser
// ceiling).
//
// SMALL BY CONSTRUCTION. Every pixel of these pictures is graphite, gold, or
// an antialiased mix of the two at some opacity, and Chromium writes that as
// full RGBA: 60–80 kB of near-identical colours. So the screenshot is
// re-encoded as an INDEXED PNG whose palette is exactly that: sixteen steps
// from graphite to gold, each at fifteen opacities, and one transparent
// entry — 241 colours, an edge with sixteen levels of antialiasing (more than
// any screen shows at the 20 to 80 px Discord draws them), and a third of the
// bytes.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { deflateSync, inflateSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { brandMarkSvg } from "../shared/brandMark.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const dir = `${root}docs/brand/presence/`;
const SIZE = 1024;
const GRAPHITE = "#0d1117";
const GOLD = "#e3b341";
const NAMES = ["mark", "pen", "page", "book", "cards", "brush", "shelf", "compass", "moon"];

const inner = brandMarkSvg({ size: 100, detail: "full", color: GOLD })
  .replace(/^<svg[^>]*>/, "")
  .replace(/<\/svg>$/, "");
writeFileSync(
  `${dir}mark.svg`,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${SIZE}" height="${SIZE}">\n` +
    `  <!-- Generated by scripts/shoot-presence-assets.mjs from shared/brandMark.ts; edit the geometry there. -->\n` +
    `  <rect width="100" height="100" rx="22" fill="${GRAPHITE}"/>\n` +
    `  <g transform="translate(12 12) scale(0.76)" fill="none" stroke="${GOLD}" stroke-linecap="round" stroke-linejoin="round">${inner}</g>\n` +
    `</svg>\n`,
);

const present = new Set(readdirSync(dir).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)));
const missing = NAMES.filter((n) => !present.has(n));
if (missing.length > 0) throw new Error(`shoot-presence-assets: no SVG for ${missing.join(", ")} in docs/brand/presence/`);

// ── PNG in, indexed PNG out ───────────────────────────────────────────────
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

/** The RGBA pixels of an 8-bit, non-interlaced, colour-type-6 PNG — what
 *  Chromium's screenshot writes — with its scanline filters undone. */
function decodeRgba(png) {
  let at = 8;
  let width = 0;
  let height = 0;
  const idat = [];
  while (at < png.length) {
    const len = png.readUInt32BE(at);
    const type = png.toString("ascii", at + 4, at + 8);
    const data = png.subarray(at + 8, at + 8 + len);
    if (type === "IHDR") {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      if (data[8] !== 8 || data[9] !== 6 || data[12] !== 0) throw new Error("shoot-presence-assets: expected an 8-bit RGBA, non-interlaced PNG");
    }
    if (type === "IDAT") idat.push(data);
    at += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * 4;
  const out = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const row = out.subarray(y * stride, (y + 1) * stride);
    const up = y > 0 ? out.subarray((y - 1) * stride, y * stride) : null;
    for (let x = 0; x < stride; x++) {
      const a = x >= 4 ? row[x - 4] : 0;
      const b = up ? up[x] : 0;
      const c = up && x >= 4 ? up[x - 4] : 0;
      let v = src[x];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      row[x] = v & 0xff;
    }
  }
  return { width, height, pixels: out };
}

const MIX_STEPS = 16; // graphite → gold
const ALPHA_STEPS = 15; // opacities above zero
const G = [0x0d, 0x11, 0x17];
const Y = [0xe3, 0xb3, 0x41];

/** The same picture as an indexed PNG over the graphite-to-gold palette. */
function indexed({ width, height, pixels }) {
  const palette = [0, 0, 0];
  const alpha = [0];
  for (let m = 0; m < MIX_STEPS; m++) {
    for (let a = 1; a <= ALPHA_STEPS; a++) {
      for (let i = 0; i < 3; i++) palette.push(Math.round(G[i] + ((Y[i] - G[i]) * m) / (MIX_STEPS - 1)));
      alpha.push(Math.round((255 * a) / ALPHA_STEPS));
    }
  }
  const rows = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y++) {
    rows[y * (width + 1)] = 0;
    for (let x = 0; x < width; x++) {
      const p = (y * width + x) * 4;
      const a = Math.round((pixels[p + 3] * ALPHA_STEPS) / 255);
      // The red channel spans graphite to gold widest (0x0d → 0xe3).
      const m = Math.max(0, Math.min(MIX_STEPS - 1, Math.round(((pixels[p] - G[0]) / (Y[0] - G[0])) * (MIX_STEPS - 1))));
      rows[y * (width + 1) + 1 + x] = a === 0 ? 0 : 1 + m * ALPHA_STEPS + (a - 1);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 3; // indexed
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("PLTE", Buffer.from(palette)),
    chunk("tRNS", Buffer.from(alpha)),
    chunk("IDAT", deflateSync(rows, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium" });
try {
  const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
  for (const name of NAMES) {
    await page.goto(`file://${dir}${name}.svg`);
    // Transparent outside the plate and the disc: Discord draws its own
    // ground behind both.
    const shot = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: SIZE, height: SIZE } });
    writeFileSync(`${dir}${name}.png`, indexed(decodeRgba(shot)));
    console.log(`wrote docs/brand/presence/${name}.png (${(statSync(`${dir}${name}.png`).size / 1024).toFixed(1)} kB)`);
  }
} finally {
  await browser.close();
}
